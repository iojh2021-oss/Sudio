#!/usr/bin/env python3
"""Train a tiny offline district-planning neural network for Sudio.
Uses only Python's standard library; emits a browser/Node JS model bundle.
"""
import json, math, random
from pathlib import Path

random.seed(73191)
INPUTS, HIDDEN, OUTPUTS = 4, 8, 4
def features(seed, index):
    return [math.sin((seed % 1000003) * .00017), math.cos((seed % 1000003) * .00017),
            math.sin(index * .37), math.cos(index * .37)]
def teacher(seed, index):
    # Synthetic design labels encode recurring district rhythms with seed variation.
    v = (math.sin(index*.31 + (seed%997)*.013) +
         .55*math.cos(index*.17 - (seed%313)*.021))
    if index % 11 == 0: return 2
    if index % 7 == 0: return 1
    if v > .55: return 0
    if v < -.55: return 3
    return 2 if v > 0 else 1

def sigmoid(x): return 1/(1+math.exp(-max(-20,min(20,x))))
def softmax(xs):
    m=max(xs); es=[math.exp(x-m) for x in xs]; s=sum(es); return [x/s for x in es]

w1=[[random.uniform(-.5,.5) for _ in range(INPUTS)] for _ in range(HIDDEN)]
b1=[0.0]*HIDDEN
w2=[[random.uniform(-.5,.5) for _ in range(HIDDEN)] for _ in range(OUTPUTS)]
b2=[0.0]*OUTPUTS
samples=[(features(seed,idx),teacher(seed,idx)) for seed in range(100,180) for idx in range(0,90)]
for epoch in range(260):
    random.shuffle(samples)
    for x,y in samples:
        h=[math.tanh(sum(w1[j][k]*x[k] for k in range(INPUTS))+b1[j]) for j in range(HIDDEN)]
        p=softmax([sum(w2[o][j]*h[j] for j in range(HIDDEN))+b2[o] for o in range(OUTPUTS)])
        d2=[p[o]-(1.0 if o==y else 0.0) for o in range(OUTPUTS)]
        d1=[(1-h[j]*h[j])*sum(d2[o]*w2[o][j] for o in range(OUTPUTS)) for j in range(HIDDEN)]
        lr=.035
        for o in range(OUTPUTS):
            for j in range(HIDDEN): w2[o][j]-=lr*d2[o]*h[j]
            b2[o]-=lr*d2[o]
        for j in range(HIDDEN):
            for k in range(INPUTS): w1[j][k]-=lr*d1[j]*x[k]
            b1[j]-=lr*d1[j]
correct=0
for x,y in samples:
    h=[math.tanh(sum(w1[j][k]*x[k] for k in range(INPUTS))+b1[j]) for j in range(HIDDEN)]
    p=softmax([sum(w2[o][j]*h[j] for j in range(HIDDEN))+b2[o] for o in range(OUTPUTS)])
    correct += max(range(OUTPUTS),key=lambda i:p[i])==y
model={"version":"tiny-mlp-1","inputSize":INPUTS,"hiddenSize":HIDDEN,"outputSize":OUTPUTS,
       "w1":w1,"b1":b1,"w2":w2,"b2":b2,"trainingAccuracy":round(correct/len(samples),4),
       "samples":len(samples),"districts":["old-town","industrial","downtown","quiet"]}
payload=json.dumps(model,separators=(",",":"),ensure_ascii=False)
Path("world-model.js").write_text("/* Generated by tools/train_world_model.py; tiny offline neural planner. */\n(function(r){r.SudioWorldModel="+payload+";})(typeof globalThis!=='undefined'?globalThis:this);\n",encoding="utf-8")
print("Trained Sudio tiny world model:", model["version"], "accuracy", model["trainingAccuracy"], "samples", len(samples))
